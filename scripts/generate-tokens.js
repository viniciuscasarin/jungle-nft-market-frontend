import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const DEFAULT_ROOT = path.resolve(__dirname, '..');

export function toKebabCase(str) {
  return str
    .replace(/([a-z])([A-Z])/g, '$1-$2')
    .replace(/([a-zA-Z])([0-9])/g, '$1-$2')
    .toLowerCase();
}

export function generateThemeCss({ rootDir = DEFAULT_ROOT } = {}) {
  const tokensPath = path.resolve(rootDir, 'design', 'tokens', 'tokens.json');
  const outDir = path.resolve(rootDir, 'libs', 'shared', 'ui', 'src', 'styles');
  const outFile = path.resolve(outDir, 'theme.css');

  if (!fs.existsSync(tokensPath)) {
    throw new Error(`Tokens file not found at ${tokensPath}`);
  }

  const tokens = JSON.parse(fs.readFileSync(tokensPath, 'utf-8'));

  const lines = [];
  lines.push('/* Auto-generated by scripts/generate-tokens.js - DO NOT EDIT MANUALLY */');
  lines.push("@import './fonts.css';");
  lines.push('');
  lines.push('@theme {');

  // 1. Colors
  lines.push('  /* --- Colors --- */');
  if (tokens.color) {
    for (const [group, items] of Object.entries(tokens.color)) {
      for (const [key, token] of Object.entries(items)) {
        const kebabKey = toKebabCase(key);
        lines.push(`  --color-${group}-${kebabKey}: ${token.value};`);
      }
    }
  }

  // Semantic aliases for Tailwind / Shadcn utilities
  lines.push('');
  lines.push('  /* --- Semantic Color Aliases --- */');
  lines.push('  --color-ink: #140d0a;');
  lines.push('  --color-surface: #140d0a;');
  lines.push('  --color-card: #241612;');
  lines.push('  --color-raised: #2f1d15;');
  lines.push('  --color-primary: #d28a4c;');
  lines.push('  --color-primary-hover: #b87437;');
  lines.push('  --color-secondary: #cfb28c;');
  lines.push('  --color-muted: #b39463;');
  lines.push('  --color-accent: #e89b55;');
  lines.push('  --color-coral: #f0805f;');
  lines.push('  --color-border: #3f2319;');
  lines.push('  --color-border-accessible: #8a583e;');
  lines.push('  --color-success: #00a66c;');
  lines.push('  --color-error: #f0805f;');

  // 2. Typography
  lines.push('');
  lines.push('  /* --- Typography: Font Family --- */');
  if (tokens.typography?.fontFamily) {
    for (const [key, token] of Object.entries(tokens.typography.fontFamily)) {
      lines.push(`  --font-${toKebabCase(key)}: ${token.value};`);
    }
  }

  lines.push('');
  lines.push('  /* --- Typography: Font Sizes --- */');
  if (tokens.typography?.fontSize) {
    for (const [key, token] of Object.entries(tokens.typography.fontSize)) {
      lines.push(`  --text-${toKebabCase(key)}: ${token.value};`);
    }
  }

  lines.push('');
  lines.push('  /* --- Typography: Font Weights --- */');
  if (tokens.typography?.fontWeight) {
    for (const [key, token] of Object.entries(tokens.typography.fontWeight)) {
      lines.push(`  --font-weight-${toKebabCase(key)}: ${token.value};`);
    }
  }

  lines.push('');
  lines.push('  /* --- Typography: Line Heights --- */');
  if (tokens.typography?.lineHeight) {
    for (const [key, token] of Object.entries(tokens.typography.lineHeight)) {
      lines.push(`  --leading-${toKebabCase(key)}: ${token.value};`);
    }
  }

  lines.push('');
  lines.push('  /* --- Typography: Letter Spacings --- */');
  if (tokens.typography?.letterSpacing) {
    for (const [key, token] of Object.entries(tokens.typography.letterSpacing)) {
      lines.push(`  --tracking-${toKebabCase(key)}: ${token.value};`);
    }
  }

  // 3. Spacing
  lines.push('');
  lines.push('  /* --- Spacing --- */');
  if (tokens.space) {
    for (const [key, token] of Object.entries(tokens.space)) {
      lines.push(`  --spacing-${key}: ${token.value};`);
    }
  }

  // 4. Radius
  lines.push('');
  lines.push('  /* --- Radius --- */');
  if (tokens.radius) {
    for (const [key, token] of Object.entries(tokens.radius)) {
      lines.push(`  --radius-${toKebabCase(key)}: ${token.value};`);
    }
  }

  // 5. Shadows
  lines.push('');
  lines.push('  /* --- Shadows --- */');
  if (tokens.shadow) {
    for (const [key, token] of Object.entries(tokens.shadow)) {
      lines.push(`  --shadow-${toKebabCase(key)}: ${token.value};`);
    }
  }

  // 6. Breakpoints
  lines.push('');
  lines.push('  /* --- Breakpoints (390, 768, 1024, 1440) --- */');
  lines.push('  --breakpoint-sm: 390px;');
  lines.push('  --breakpoint-md: 768px;');
  lines.push('  --breakpoint-lg: 1024px;');
  lines.push('  --breakpoint-xl: 1280px;');
  lines.push('  --breakpoint-mobile: 390px;');
  lines.push('  --breakpoint-tablet: 768px;');
  lines.push('  --breakpoint-desktop: 1440px;');

  lines.push('}');
  lines.push('');

  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(outFile, lines.join('\n'), 'utf-8');

  return { outFile, tokenCount: lines.length };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log('Compilando tokens do Figma para theme.css (Tailwind v4)...');
  const result = generateThemeCss();
  console.log(`[OK] Tema gerado com sucesso em: ${result.outFile}`);
}
